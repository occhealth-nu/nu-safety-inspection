-- สร้าง "รหัสนำเข้า" สำหรับ Google Sheets (Apps Script)
-- วิธีใช้: Run แล้วคัดลอกรหัสที่ขึ้นต้นด้วย nuimp_ จากช่องผลลัพธ์ → ใส่ในเมนู NU Safety › ตั้งค่าการเชื่อมต่อ
--   • รหัสแสดงครั้งเดียว (ระบบเก็บเฉพาะค่า hash) — ถ้าทำหาย ให้รันไฟล์นี้ใหม่เพื่อสร้างรหัสใหม่
--   • รหัสนี้ทำได้เฉพาะนำเข้าข้อมูลและดึงรายงาน — ห้ามส่งทางแชต/อีเมล เก็บเฉพาะใน Apps Script
--   • ยกเลิกรหัสทั้งหมด (เช่น เปลี่ยนผู้ดูแล/สงสัยว่ารั่ว):  select app.revoke_import_keys();
--   • ดูรหัสที่มีอยู่: select name, key_hint, created_at, last_used_at, use_count, revoked_at from app.import_keys;
-- =====================================================================
